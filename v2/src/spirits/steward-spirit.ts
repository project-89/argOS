/**
 * Check if a room needs replenishment
 */
export function checkRoomNeeds(roomName: string, currentEntities: string[]): {
  missing: string[];
  depleted: string[];
  recommendations: string[];
} {
  const originalEntities = stewardState.roomInventory.get(roomName) || [];
  const missing = originalEntities.filter(e => !currentEntities.includes(e));

  // Find depleted resources (would need quantity tracking from ECS)
  const depleted: string[] = [];

  // Generate recommendations
  const recommendations: string[] = [];
  if (missing.length > 0) {
    recommendations.push(`Replenish missing items: ${missing.join(", ")}`);
  }

  return { missing, depleted, recommendations };
}

