/**
 * The Steward Spirit - Room Population & Maintenance
 *
 * When GodAI creates a location, The Steward receives the room specification and:
 * 1. Generates appropriate entities (objects, items, furniture, resources)
 * 2. Ensures descriptions match actual entity contents
 * 3. Maintains room coherence over time
 * 4. Requests systems/components from The Weaver when needed
 *
 * The key principle: If a room description says "flour sacks line the walls",
 * there MUST be flour_sack entities. Agents should never perceive things that
 * don't exist in the ECS.
 */

