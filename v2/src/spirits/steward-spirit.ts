/**
 * Generate a populated room specification using AI
 */
export async function generateRoomPopulation(
  request: RoomCreationRequest
): Promise<PopulatedRoom | null> {
  const model = spiritModel;

  // Get template hints if available
  const template = ROOM_TEMPLATES[request.roomType.toLowerCase().replace(/\s+/g, "_")];

  const templateHint = template
    ? `
TEMPLATE HINTS for ${request.roomType}:
- Core items typically found: ${template.coreItems.join(", ")}
- Optional items: ${template.optionalItems.join(", ")}
- Work stations: ${template.stations.join(", ")}
- Typical sounds: ${template.ambience.sounds.join(", ")}
- Typical smells: ${template.ambience.smells.join(", ")}
`
    : "";

  const prompt = `You are The Steward, a spirit responsible for furnishing and populating rooms in a living simulation.

TASK: Generate a complete entity manifest for "${request.roomName}" (a ${request.roomType}).

CONTEXT:
- World theme: ${request.context.worldTheme || "medieval fantasy"}
- Economy level: ${request.context.economyLevel || "modest"}
- Primary function: ${request.context.primaryFunction || `A working ${request.roomType}`}
- Inhabitants: ${request.context.inhabitants?.join(", ") || "Various villagers"}
${templateHint}

CONSTRAINTS:
- Max items: ${request.constraints?.maxItems || 15}
- Budget: ${request.constraints?.budgetLevel || "normal"}
${request.constraints?.requiredItems?.length ? `- MUST include: ${request.constraints.requiredItems.join(", ")}` : ""}
${request.constraints?.forbiddenItems?.length ? `- MUST NOT include: ${request.constraints.forbiddenItems.join(", ")}` : ""}

RULES:
1. Generate 8-15 entities that would realistically be in this room
2. Each entity must be concrete and tangible - no abstract concepts
3. Include a mix of: furniture, tools, resources/consumables, containers, decorations
4. Resources should have quantities (e.g., "flour_sack" with quantity 50)
5. Mark items as portable (can be picked up) or not
6. Consider what agents would actually need to DO their job here

CRITICAL - STIMULUS-BASED PERCEPTION:
Instead of static descriptions, each entity EMITS STIMULI that agents perceive.
- A lit forge emits: visual ("Glowing coals illuminate the forge"), heat ("Waves of heat radiate from the forge"), sound ("The fire crackles and roars")
- Fresh bread emits: visual ("Golden loaves cool on the rack"), smell ("The aroma of fresh-baked bread fills the air")
- An anvil might emit: visual ("A heavy iron anvil sits ready"), sound (only when in use - leave empty if idle)

Agents perceive rooms DYNAMICALLY through what's emitting. No static room descriptions!

Respond with a JSON object in this exact format:
{
  "entities": [
    {
      "name": "entity_name_snake_case",
      "type": "object|furniture|container|resource|tool|decoration|station",
      "description": "Brief internal description for WorldSchema",
      "material": "wood|iron|stone|cloth|glass|leather|etc",
      "quantity": null or number for consumables,
      "portable": true/false,
      "interactable": true/false,
      "affordances": ["action1", "action2"],
      "stimuli": [
        {
          "type": "visual|smell|sound|heat|cold|tactile",
          "template": "What agents perceive, written as sensory description",
          "intensity": 0.1 to 1.0 (how noticeable)
        }
      ]
    }
  ],
  "ambientStimuli": [
    {
      "type": "sound|smell|visual",
      "template": "Room-level ambient stimuli not tied to specific objects, e.g., 'Dust motes drift in the light'",
      "intensity": 0.3
    }
  ],
  "systemRequests": [
    {
      "type": "system|component",
      "name": "name of system/component needed",
      "reason": "why this is needed for the room to function"
    }
  ] or empty array if none needed
}`;

  try {
    const response = await generateText({
      model,
      prompt,
      temperature: 0.7,
    });

    // Parse JSON from response
    const jsonMatch = response.text.match(/\{[\s\S]*\}/);
    if (!jsonMatch) {
      console.error("[Steward] Failed to extract JSON from response");
      return null;
    }

    const parsed = JSON.parse(jsonMatch[0]);

    // Parse stimuli with defaults
    const parseStimuli = (stimuliArray: any[]): StimulusEmission[] => {
      if (!stimuliArray || !Array.isArray(stimuliArray)) return [];
      return stimuliArray.map((s: any) => ({
        type: s.type || "visual",
        template: s.template || "",
        interval: s.interval ?? 5000,
        intensity: s.intensity ?? 0.5,
      }));
    };

    const populatedRoom: PopulatedRoom = {
      requestId: request.id,
      roomName: request.roomName,
      roomType: request.roomType,
      entities: parsed.entities.map((e: any) => ({
        name: e.name,
        type: e.type,
        description: e.description,
        material: e.material,
        quantity: e.quantity,
        portable: e.portable ?? false,
        interactable: e.interactable ?? true,
        affordances: e.affordances || [],
        stimuli: parseStimuli(e.stimuli),
        components: inferComponents(e),
      })),
      ambientStimuli: parseStimuli(parsed.ambientStimuli),
      // Legacy support - convert old ambience to stimuli if present
      ambience: parsed.ambience,
      generatedDescription: parsed.generatedDescription, // Optional, for debugging
      systemRequests: parsed.systemRequests || [],
      timestamp: Date.now(),
      status: "pending",
    };

    // Track entities for this room
    stewardState.roomInventory.set(
      request.roomName,
      populatedRoom.entities.map(e => e.name)
    );

    // Remove from pending, add to completed
    stewardState.pendingRequests = stewardState.pendingRequests.filter(
      r => r.id !== request.id
    );
    stewardState.completedRooms.push(populatedRoom);

    // Track system requests
    if (populatedRoom.systemRequests && populatedRoom.systemRequests.length > 0) {
      stewardState.systemRequests.push(...populatedRoom.systemRequests);
    }

    console.log(`[Steward] Generated ${populatedRoom.entities.length} entities for ${request.roomName}`);

    return populatedRoom;
  } catch (error) {
    console.error("[Steward] Error generating room population:", error);
    return null;
  }
}

/**
 * Infer which ECS components an entity should have based on its type
 */
function inferComponents(entity: any): string[] {
  const components: string[] = ["Name", "Description"];

  switch (entity.type) {
    case "resource":
      components.push("Consumable");
      if (entity.quantity) components.push("Quantity");
      break;
    case "container":
      components.push("Container", "Inventory");
      break;
    case "tool":
      components.push("Tool", "Usable");
      break;
    case "station":
      components.push("Station", "Interactable");
      break;
    case "furniture":
      components.push("Furniture");
      break;
    case "decoration":
      components.push("Decoration");
      break;
  }

  if (entity.portable) {
    components.push("Portable");
  }

  if (entity.interactable) {
    components.push("Interactable");
  }

  // Add StimulusSource if entity has stimuli
  if (entity.stimuli && entity.stimuli.length > 0) {
    components.push("StimulusSource");
  }

  return components;
}

