/**
 * A room creation request delegated from GodAI
 */
export interface RoomCreationRequest {
  /** Diagnostic identifier only. Authority resides in the host's request scope. */
  observationScopeId?: string;
  id: string;
  timestamp: number;
  requestedBy: number; // Spirit EID (usually God)
  roomType: string; // e.g., "bakery", "blacksmith", "tavern"
  roomName: string;
  context: {
    worldTheme?: string; // e.g., "medieval fantasy", "cyberpunk"
    economyLevel?: "poor" | "modest" | "prosperous" | "wealthy";
    primaryFunction?: string; // What the room is for
    inhabitants?: string[]; // Who will use this room
    connectedRooms?: string[]; // Nearby rooms for context
  };
  constraints?: {
    /** Maximum constructed entities, including ambient sources and native fallbacks. */
    maxItems?: number;
    requiredItems?: string[]; // Must include these
    forbiddenItems?: string[]; // Must NOT include these
    budgetLevel?: "sparse" | "normal" | "abundant";
  };
}

/**
 * Stimulus emission definition for an entity
 */
export interface StimulusEmission {
  type: "visual" | "smell" | "sound" | "heat" | "cold" | "tactile";
  template: string; // What agents perceive, e.g., "The forge glows with hot coals"
  interval?: number; // Emission interval in ms (default: 5000)
  intensity?: number; // 0-1, affects perception priority (default: 0.5)
}

/**
 * An entity specification generated by The Steward
 */
export interface RoomEntitySpec {
  name: string;
  type: "object" | "furniture" | "container" | "resource" | "tool" | "decoration" | "station";
  description: string; // Internal description (for WorldSchema)
  material?: string;
  quantity?: number; // For resources/consumables
  portable: boolean;
  interactable: boolean;
  affordances?: string[]; // What can be done with this
  components?: string[]; // ECS components to add

  // Stimulus-based perception (dynamic, not static)
  stimuli: StimulusEmission[]; // What this entity emits for agents to perceive
}

/**
 * A fully populated room specification
 */
export interface PopulatedRoom {
  requestId: string;
  roomName: string;
  roomType: string;

  // Entities to create (each with their own stimuli)
  entities: RoomEntitySpec[];

  // Ambient stimulus sources (room-level stimuli not tied to specific objects)
  ambientStimuli: StimulusEmission[];

  // Legacy support (optional) - can be used for debugging
  generatedDescription?: string;

  // Legacy ambience (converted to ambientStimuli internally)
  ambience?: {
    sounds?: string[];
    smells?: string[];
    lighting?: string;
    temperature?: string;
  };

  // What systems/components might be needed
  systemRequests?: SystemRequest[];

  // Metadata
  timestamp: number;
  status: "pending" | "created" | "failed";
}

/**
 * A request for The Weaver to create new systems/components
 */
export interface SystemRequest {
  type: "system" | "component";
  name: string;
  reason: string;
  specification?: string;
}

