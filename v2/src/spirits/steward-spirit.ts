/**
 * Send system requests to The Weaver
 */
export function sendSystemRequestsToWeaver(registry: SpiritRegistry): number {
  const pendingRequests = stewardState.systemRequests.filter(
    r => !r.specification // Not yet sent
  );

  if (pendingRequests.length === 0) return 0;

  // Find The Steward and The Weaver spirits
  const steward = registry.byName.get("The Steward");
  const weaver = registry.byName.get("The Weaver");

  if (!steward || !weaver) {
    console.warn("[Steward] Cannot send requests - spirits not found");
    return 0;
  }

  // Get the actual spirit states
  const stewardSpirit = registry.spirits.get(steward);
  const weaverSpirit = registry.spirits.get(weaver);

  if (!stewardSpirit || !weaverSpirit) {
    console.warn("[Steward] Cannot send requests - spirit states not found");
    return 0;
  }

  for (const request of pendingRequests) {
    const message: DivineMessage = {
      id: `steward_req_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
      timestamp: Date.now(),
      from: steward,
      to: weaver,
      type: "request",
      domain: "locale",
      priority: "normal",
      subject: `${request.type === "system" ? "System" : "Component"} Request: ${request.name}`,
      content: `The Steward requests a new ${request.type} to support room functionality.\n\nName: ${request.name}\nReason: ${request.reason}`,
      requiresResponse: true,
    };

    // Push directly to The Weaver's inbox
    weaverSpirit.inbox.push(message);

    // Mark as sent
    request.specification = "sent";
  }

  console.log(`[Steward] Sent ${pendingRequests.length} system requests to The Weaver`);
  return pendingRequests.length;
}

