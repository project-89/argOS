let requestIdCounter = 0;

/**
 * Submit a room creation request to The Steward
 */
export function requestRoomPopulation(
  roomType: string,
  roomName: string,
  context: RoomCreationRequest["context"] = {},
  constraints: RoomCreationRequest["constraints"] = {},
  requestedBy: number = 0
): RoomCreationRequest {
  const request: RoomCreationRequest = {
    id: `room_${++requestIdCounter}_${Date.now()}`,
    timestamp: Date.now(),
    requestedBy,
    roomType,
    roomName,
    context,
    constraints,
  };

  stewardState.pendingRequests.push(request);
  console.log(`[Steward] Room population request received: ${roomName} (${roomType})`);

  return request;
}

/**
 * Get pending room requests
 */
export function getPendingRoomRequests(): RoomCreationRequest[] {
  return stewardState.pendingRequests;
}

